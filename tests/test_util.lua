-- F14(真机反馈 2026-09-13):自适应文本宽度估算与成对数值行拆分的单元测试。
local U = require("pickthought.util")

T.case("text_px 估算:中文 1em、数字 0.55em、字母 0.6em(F14)", function()
    T.eq(U.text_px("划线条", 20), 60, "3 个 CJK 字按 1em")
    T.eq(U.text_px("1234567890", 20), 110, "10 个数字按 0.55em")
    T.eq(U.text_px("abc", 20), 36, "3 个字母按 0.6em")
    T.ok(U.text_px("划线 12,537 条，想法 35,379 条", 34)
        > U.text_px("划线 12 条，想法 35 条", 34), "大数字估算更宽")
    T.eq(U.text_px("", 20), 0, "空文本为零")
end)

T.case("pair_line:宽裕单行、超宽拆两行、无宽度信息保持单行(F14)", function()
    T.eq(U.pair_line("本轮已匹配：划线 1 条", "想法 2 条", 10000, 20),
        "本轮已匹配：划线 1 条，想法 2 条", "宽裕时保持单行")
    T.eq(U.pair_line("本轮已匹配：划线 12,537 条", "想法 35,379 条", 200, 20),
        "本轮已匹配：划线 12,537 条\n想法 35,379 条", "超宽时在分隔处拆两行,前缀保留在首行")
    T.eq(U.pair_line("划线 12,537 条", "想法 35,379 条", 200, 20),
        "划线 12,537 条\n想法 35,379 条", "无前缀时直接拆两行")
    T.eq(U.pair_line("划线 1 条", "想法 2 条", nil, 20),
        "划线 1 条，想法 2 条", "无宽度信息(如测试桩环境)保持单行")
    T.eq(U.pair_line("划线 1 条", "想法 2 条", 0, 20),
        "划线 1 条，想法 2 条", "宽度为 0 视为无信息")
end)
